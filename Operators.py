#Arithmetic operators
a=20
b=40
print("Addition:",a+b)
print("Subtraction:",a-b)
print("Multiplication:",a*b)
print("Division:",a/b)
print("Floor Division:",a//b)
print("Modulus:",a%b)
print("Exponentiation:",a**b)

#Comparison operators
a=20
b=12
print(a>b)
print(a<b)
print(a==b)
print(a!=b)
print(a<=b)
print(a>=b)

#Logical operators
a=True
b=False
print(a and b)
print(a or b)
print(not b)

#Assignment operators
a=20
b=a
print(b)
b+=a
print(b)
b-=a
print(b)
b<<=a
print(b)

#Bitwise operators
a=30
b=10
print(a&b)
print(a|b)
print(~a)
print(a^b)
print(a>>2)
print(a<<2)

#Identity operators
a=20
b=12
c=45
print(a is not b)
print(a is c)

#Membership operators
a=[1,2,3,4,5]
print(2 not in a)
print(1 in a)

#Operator associativity
print(20/10+2)
print(2-4+2)
print(7-(2-6))
print(1**3**2)

